// Real browser → local API → isolated SQLite → progress UI. Only fictional provider responses.
import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const require=createRequire(resolve(process.env.CONTEXTGUARD_PLAYWRIGHT_PACKAGE||'../frontend/package.json'));
const {chromium,expect}=require('@playwright/test');
const base=process.env.CONTEXTGUARD_URL||'http://127.0.0.1:8046';
const output='artifacts/processing-ui';await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const errors=[],checks=[];
let page;
try{
  const context=await browser.newContext({viewport:{width:1440,height:1100}});
  page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
  await context.request.post(base+'/api/setup',{data:{username:'Progress owner',password:'fictional-progress-password'}});
  await context.request.post(base+'/api/login',{data:{username:'Progress owner',password:'fictional-progress-password'}});
  const project=await (await context.request.post(base+'/api/command',{data:{action:'project',payload:{name:'Synora',
    description:'Fictional first pilot: dates, Atlas, memory review and routing.'}}})).json();
  await page.goto(base);await expect(page.getByRole('heading',{name:'Project reviews',exact:true})).toBeVisible();
  const files=['01-product-brief.md','02-architecture-notes.md','03-meeting-notes.md','04-release-checklist.md','05-integration-scope.md','06-project-lead-email.md'];
  await page.getByLabel('Documents or exported conversations').setInputFiles(files.map(name=>resolve('samples/synora-all-sources',name)));
  await page.getByLabel('I am authorized to process this selected content.').check();
  await page.getByLabel('Allow model providers to process this content, project descriptions and matched-project decisions.').check();
  let releaseUpload,uploads=0;
  const hold=new Promise(resolve=>{releaseUpload=resolve;});
  await page.route('**/api/intakes/upload',async route=>{uploads++;await hold;await route.continue();});
  const response=page.waitForResponse(r=>r.url().endsWith('/api/intakes/upload')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Process content',exact:true}).click();
  const banner=page.locator('#processing-overview');
  await expect(banner).toContainText('Uploading and preparing documents');
  await expect(page.getByRole('button',{name:'Processing…',exact:true})).toBeDisabled();
  expect(await banner.evaluate(node=>node.getBoundingClientRect().bottom<=document.querySelector('.review-intake-grid').getBoundingClientRect().top)).toBe(true);
  await page.locator('form[data-form=capture]').dispatchEvent('submit');
  expect(uploads).toBe(1);
  await page.screenshot({path:output+'/uploading-desktop.png',fullPage:true});
  releaseUpload();const upload=await response;expect(upload.status()).toBe(202);const started=await upload.json();
  await expect(banner).toContainText('Matching passages to projects',{timeout:15000});
  await page.reload();
  await expect(page.locator('#processing-overview')).toContainText('Matching passages to projects',{timeout:15000});
  await expect(page.getByRole('button',{name:'Processing…',exact:true})).toBeDisabled();
  checks.push('Six real sample files: immediate upload indicator above form, duplicate prevention and active-job restoration after reload');
  await expect(page.locator('#processing-overview')).toContainText('Analyzing findings',{timeout:20000});
  await expect(page.locator('#processing-overview')).toContainText('passages checked for project relevance');
  await page.screenshot({path:output+'/analyzing-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:1000});
  await page.screenshot({path:output+'/analyzing-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.setViewportSize({width:1440,height:1100});
  await expect(page.locator('#processing-overview')).toContainText('Review complete',{timeout:30000});
  await expect(page.getByRole('button',{name:'Process content',exact:true})).toBeEnabled();
  const finished=await (await context.request.get(base+'/api/intakes/'+started.id)).json();
  expect(finished.status).toBe('complete');expect(finished.project_ids).toEqual([project.id]);
  expect(finished.units_processed).toBe(finished.units_total);
  await page.getByRole('button',{name:'Open review',exact:true}).click();
  await expect(page.locator('.review-toolbar')).toBeVisible();
  checks.push('Actual API routing/analysis stage changes, real counts, mobile layout, completion and resulting stored review link');
  await page.getByRole('button',{name:'Back to reviews',exact:true}).click();
  await page.locator('.paste-option summary').click();
  await page.getByLabel('Complete conversation',{exact:true}).fill('Synora FAIL_PROGRESS_CHECK: Fictional approval is pending.');
  await page.getByLabel('I am authorized to process this selected content.').check();
  await page.getByLabel('Allow model providers to process this content, project descriptions and matched-project decisions.').check();
  await page.getByRole('button',{name:'Process content',exact:true}).click();
  await expect(page.locator('#processing-overview')).toContainText('Processing needs attention',{timeout:15000});
  await expect(page.locator('#processing-overview')).toContainText('Controlled progress check: model unavailable. Input retained.');
  await expect(page.getByRole('button',{name:'Retry retained input',exact:true})).toBeVisible();
  await expect(page.locator('#processing-overview .processing-record').first().locator('[data-review]')).toHaveCount(0);
  const failedId=await page.locator('#processing-overview [data-processing-job]').first().getAttribute('data-processing-job');
  const beforeRetry=await (await context.request.get(base+'/api/intakes/'+failedId)).json();
  const retriedResponse=page.waitForResponse(r=>r.url().endsWith('/retry')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Retry retained input',exact:true}).click();
  expect((await retriedResponse).status()).toBe(202);
  await expect(page.locator('#processing-overview')).toContainText('Processing needs attention',{timeout:15000});
  await expect(page.locator('#app')).toHaveAttribute('aria-busy','false');
  const afterRetry=await (await context.request.get(base+'/api/intakes/'+failedId)).json();
  expect(afterRetry.attempt).toBe(beforeRetry.attempt+1);
  await expect(page.locator('#processing-overview .processing-clock').first()).toHaveAttribute('data-processing-start',afterRetry.attempt_started);
  await page.screenshot({path:output+'/failure-and-retry.png',fullPage:true});
  checks.push('Provider failure remains visible, preserves retry and never labels partial output as a completed review');
  await page.locator('.paste-option summary').click();
  await page.getByLabel('Complete conversation',{exact:true}).fill('');
  await page.getByLabel('Documents or exported conversations').setInputFiles(resolve('samples/synora-all-sources',files[0]));
  await page.getByLabel('I am authorized to process this selected content.').check();
  await page.getByLabel('Allow model providers to process this content, project descriptions and matched-project decisions.').check();
  await page.route('**/api/intakes/upload',route=>route.fulfill({status:422,json:{detail:'Controlled upload validation failure.'}}));
  await page.getByRole('button',{name:'Process content',exact:true}).click();
  await expect(page.locator('#processing-overview')).toContainText('Upload needs attention');
  await expect(page.locator('#processing-overview')).toContainText('Controlled upload validation failure.');
  await expect(page.getByRole('button',{name:'Process content',exact:true})).toBeEnabled();
  expect(await page.getByLabel('Documents or exported conversations').evaluate(node=>node.files.length)).toBe(1);
  checks.push('Upload rejection shows a persistent error and restores the submit button without losing the selected file');
  expect(errors).toEqual([]);
  await writeFile(output+'/results.json',JSON.stringify({checks,errors,mode:'Fictional delayed providers; real local API/storage; no external services'},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
}catch(error){if(page)await page.screenshot({path:output+'/failure.png',fullPage:true}).catch(()=>{});console.error(error.stack);process.exitCode=1;}
finally{await browser.close();}
