import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const require = createRequire(resolve('frontend/package.json'))
const { chromium, expect } = require('@playwright/test')
const base = process.env.CONTEXTGUARD_MEMORY_TEST_URL || 'http://127.0.0.1:8019'
const folder = 'artifacts/project-memory'
await mkdir(folder, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const result = { mode: 'Isolated database with controlled model responses; no live Mem0 service or model calls', checks: [], errors: [] }
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
  page.on('pageerror', error => result.errors.push(error.message))
  await page.goto(base)
  await expect(page.locator('.local-note')).toHaveCount(0)
  await expect(page.locator('.sidebar-bottom')).toHaveCount(0)
  const list = await page.locator('.saved-reviews').boundingBox()
  expect(list.y + list.height).toBeGreaterThan(1050)
  const settings = page.getByRole('button', { name: 'Providers & privacy', exact: true })
  const box = await settings.boundingBox()
  expect(box.x).toBeGreaterThan(1000)
  await settings.click()
  await expect(page.getByRole('heading', { name: 'Project memory', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  result.checks.push('Sidebar note removed, recent reviews use available height, provider settings work at navbar right')
  await page.getByRole('button', { name: 'New review', exact: true }).click()
  await page.getByLabel('Review name', { exact: true }).fill('Synora follow-up - controlled browser test')
  await page.getByLabel('Project', { exact: true }).selectOption({ label: 'Synora - memory browser test' })
  await page.getByLabel('What are you deciding?', { exact: true }).fill('Should we change the Synora pilot date?')
  await page.getByRole('button', { name: 'Save decision', exact: true }).click()
  const panel = page.getByRole('region', { name: 'Earlier project decisions', exact: true })
  await expect(panel.getByText('January 18, 2027 is the selected pilot target.', { exact: true })).toBeVisible()
  await panel.getByText('Source references', { exact: true }).click()
  await expect(panel.getByText(/04-release-checklist.md/)).toBeVisible()
  await page.getByLabel('Upload source file').setInputFiles({ name: 'synora-follow-up.md', mimeType: 'text/markdown', buffer: Buffer.from('The revised Synora pilot proposal is December 7, 2026. Confirm whether this replaces the earlier target.') })
  await expect(page.getByText('1 / 8 sources', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Review the evidence', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Confirm whether the earlier pilot target changed', exact: true }).last()).toBeVisible()
  const id = await page.evaluate(() => localStorage.getItem('contextguard.active'))
  let data = await (await page.request.get(`${base}/api/cases/${id}`)).json()
  expect(data.report.prior_decisions).toHaveLength(1)
  expect(data.report.findings[0].status).toBe('open')
  await page.getByRole('button', { name: 'Prepare brief', exact: true }).click()
  await expect(page.getByLabel('Brief text', { exact: true })).toHaveValue(/Earlier project decisions considered/)
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.screenshot({ path: `${folder}/earlier-decisions-desktop.png`, fullPage: true })
  result.checks.push('Same-project recall shows exact answer and original source quotes; analysis gets historical context without auto-closing the current finding; brief records prior context')
  await page.reload()
  await expect(page.getByRole('region', { name: 'Earlier project decisions' }).getByText('January 18, 2027 is the selected pilot target.', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await expect(page.getByRole('button', { name: 'Providers & privacy', exact: true })).toBeVisible()
  await page.screenshot({ path: `${folder}/earlier-decisions-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1100 })
  await page.getByRole('button', { name: 'New review', exact: true }).click()
  await page.getByLabel('Project', { exact: true }).selectOption({ label: 'Separate product - memory browser test' })
  await page.getByRole('button', { name: 'Save decision', exact: true }).click()
  await expect(page.getByText('No earlier clarifications in this project yet.', { exact: false })).toBeVisible()
  await expect(page.getByText('January 18, 2027 is the selected pilot target.', { exact: true })).toHaveCount(0)
  await page.locator('.project-create summary').click()
  await page.getByLabel('New project name', { exact: true }).fill('Project created from browser')
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(page.getByLabel('Project', { exact: true }).locator('option:checked')).toHaveText('Project created from browser')
  await page.getByRole('button', { name: 'Save decision', exact: true }).click()
  result.checks.push('Recall survives reload, remains usable at 390px, does not leak into a different project, and supports creating/selecting a project in setup')
  expect(result.errors).toEqual([])
  result.passed = true
} catch (error) {
  result.passed = false; result.error = error.message; process.exitCode = 1
} finally {
  await writeFile(`${folder}/browser-results.json`, JSON.stringify(result, null, 2))
  console.log(JSON.stringify(result, null, 2))
  await browser.close()
}
