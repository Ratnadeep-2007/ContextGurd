import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const require = createRequire(resolve('frontend/package.json'))
const { chromium, expect } = require('@playwright/test')
const base = process.env.CONTEXTGUARD_URL || 'http://127.0.0.1:8017'
const folder = 'artifacts/clarification-options'
await mkdir(folder, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const results = { checks: [], errors: [], mode: 'Fictional sample replay; no live AI detection claim' }
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
  page.on('pageerror', error => results.errors.push(error.message))
  await page.goto(base)
  await page.getByRole('button', { name: 'Try a sample review', exact: true }).click()
  await expect(page.getByText('4 decisions need attention', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Important.*The release date needs confirmation/ }).click()
  const choices = page.getByRole('combobox', { name: 'Choose an answer', exact: true })
  await expect(page.locator('.resolution-form select')).toHaveCount(1)
  await expect(page.getByRole('radio')).toHaveCount(0)
  await expect(choices).toHaveValue('')
  await expect(choices.locator('option').last()).toHaveText('Other')
  const ownerBox = await page.getByLabel('Who can clarify this?').boundingBox()
  const choiceBox = await choices.boundingBox()
  expect(ownerBox.y).toBeLessThan(choiceBox.y)
  await choices.focus()
  await page.keyboard.press('ArrowDown')
  await expect(choices).toHaveValue(/source_/)
  await choices.selectOption('other')
  await page.getByLabel('Your answer', { exact: true }).fill('A custom answer that will not be submitted when a source choice is selected.')
  await choices.selectOption({ label: 'November 20, 2026' })
  await expect(page.getByLabel('Your answer', { exact: true })).toHaveCount(0)
  await page.getByLabel('Who can clarify this?').fill('Sample project lead')
  await page.screenshot({ path: `${folder}/source-options-desktop.png`, fullPage: true })
  await page.getByRole('button', { name: 'Save & recheck', exact: true }).click()
  await expect(page.getByText('3 decisions need attention', { exact: true })).toBeVisible()
  await page.reload()
  await page.locator('.finding-item').filter({ hasText: 'The release date needs confirmation' }).click()
  await expect(page.getByRole('combobox', { name: 'Choose an answer', exact: true }).locator('option:checked')).toHaveText('November 20, 2026')
  const id = await page.evaluate(() => localStorage.getItem('contextguard.active'))
  const load = async () => (await page.request.get(`${base}/api/cases/${id}`)).json()
  let review = await load()
  const selected = review.report.findings.find(f => f.check_id === 'dates')
  expect(selected.status).toBe('user_confirmed')
  expect(selected.option_text).toBe(selected.answer)
  expect(selected.option_passage_ids.length).toBeGreaterThan(0)
  expect(review.resolutions[0].option_evidence_ids.length).toBeGreaterThan(0)
  const hashes = review.sources.map(s => s.content_hash)
  results.checks.push('Owner first, one context dropdown, keyboard selection, Other last with conditional text, and saved choice/provenance after reload')
  for (const finding of review.report.findings.filter(f => f.status === 'open')) {
    await page.locator('.finding-item').filter({ hasText: finding.title }).click()
    await page.getByRole('combobox', { name: 'Choose an answer', exact: true }).selectOption('other')
    await page.getByLabel('Your answer', { exact: true }).fill(`Fictional clarification recorded for: ${finding.title}`)
    await page.getByRole('button', { name: 'Save & recheck', exact: true }).click()
    await expect(page.locator('.progress-panel')).toHaveCount(0)
    await expect(page.locator('.recorded')).toBeVisible()
  }
  await expect(page.getByText('No open decisions in assessed checks', { exact: true })).toBeVisible()
  review = await load()
  expect(review.sources.map(s => s.content_hash)).toEqual(hashes)
  expect(review.resolutions).toHaveLength(4)
  await page.getByRole('button', { name: 'Prepare brief', exact: true }).click()
  const brief = page.getByLabel('Brief text', { exact: true })
  await expect(brief).toHaveValue(/User-confirmed clarifications: 4/)
  await expect(brief).toHaveValue(/Still unanswered: 0/)
  await expect(brief).toHaveValue(/Recorded clarifications/)
  await expect(brief).toHaveValue(/Choice source:/)
  await expect(brief).toHaveValue(/Limitations/)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download Markdown', exact: true }).click()
  await (await download).saveAs(`${folder}/all-clarified-brief.md`)
  await page.screenshot({ path: `${folder}/all-clarified-brief.png`, fullPage: true })
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.finding-item').filter({ hasText: selected.title }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: `${folder}/source-options-mobile.png`, fullPage: true })
  results.checks.push('All four sample findings clarified; final brief groups decisions and preserves source choice, owner, and limits; mobile has no overflow')
  await page.getByRole('button', { name: 'History', exact: true }).click()
  const history = page.getByRole('dialog')
  await expect(history.getByText(selected.answer, { exact: true })).toBeVisible()
  await history.getByRole('button', { name: 'Undo this choice', exact: true }).last().click()
  await expect(page.getByText('1 decisions need attention', { exact: true })).toBeVisible()
  results.checks.push('Choice remains in history and can be undone')
  expect(results.errors).toEqual([])
  results.passed = true
} catch (error) {
  results.passed = false
  results.failure = error.message
  process.exitCode = 1
} finally {
  await writeFile(`${folder}/results.json`, JSON.stringify(results, null, 2))
  console.log(JSON.stringify(results, null, 2))
  await browser.close()
}
